def main() -> int:
    raw = json.loads(CASES_PATH.read_text(encoding="utf-8"))
    cases = {c["id"]: c for c in raw["cases"]}
    before = len(cases)

    modified = 0
    for cid, patch in PATCHES.items():
        if cid not in cases:
            raise SystemExit(f"补丁目标不存在：{cid}")
        cases[cid].update(patch)
        modified += 1

    added = 0
    for item in NEW_CASES:
        if item["id"] in cases:
            raise SystemExit(f"新增案例编号冲突：{item['id']}")
        cases[item["id"]] = item
        added += 1

    ordered = [{k: cases[cid].get(k) for k in CASE_FIELDS} for cid in sorted(cases)]
    raw["cases"] = ordered
    raw["version"] = "2.2.0"
    raw["updated_at"] = "2026-11-11"
    CASES_PATH.write_text(json.dumps(raw, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"修改 {modified} 条，新增 {added} 条，删除 0 条；案例总数 {before} -> {len(ordered)}")
    equipments = sorted({c["equipment"] for c in ordered})
    print(f"设备类型 {len(equipments)} 类：{'、'.join(equipments)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
